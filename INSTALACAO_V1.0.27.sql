CREATE TABLE AD_CONF_CARGA_ACAO (
  NUACAO NUMBER(15) NOT NULL,
  NUCONF NUMBER(15) NOT NULL,
  ACAO VARCHAR2(30) NOT NULL,
  STATUS_ANT VARCHAR2(1) NOT NULL,
  STATUS_NOVO VARCHAR2(1) NOT NULL,
  CODUSU NUMBER(10) NOT NULL,
  DHACAO DATE DEFAULT SYSDATE NOT NULL,
  JUSTIFICATIVA VARCHAR2(500),
  CONSTRAINT PK_AD_CONF_CARGA_ACAO PRIMARY KEY (NUACAO)
);
CREATE INDEX IX_AD_CONF_CARGA_ACAO_01 ON AD_CONF_CARGA_ACAO (NUCONF,DHACAO);
CREATE SEQUENCE AD_CONF_CARGA_ACAO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
